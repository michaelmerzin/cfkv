"""Error-bar table from results/raw/errbars_*: five independent calibration samples per model and depth. For MMLU (1,000) and
GSM8K (500): full model, POP, CF-KV mean +- s.d. over the five refits, and the gain of CF-KV over POP with a paired bootstrap 95%
interval over items (per-item CF-KV correctness averaged over the refits; 10,000 resamples). Writes paper/table_errbars.tex."""
import glob, json, os
import numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = {"qwen1.5b": ("Qwen2.5-1.5B", 28), "qwen7b": ("Qwen2.5-7B", 28), "llama8b": ("Llama-3.1-8B", 32), "mistral7b": ("Mistral-7B", 32)}
ORDER = ["qwen1.5b", "qwen7b", "llama8b", "mistral7b"]
rng = np.random.default_rng(0)

def boot(diff, n=10000):
    idx = rng.integers(0, len(diff), size=(n, len(diff)))
    m = diff[idx].mean(1)
    return 100 * diff.mean(), 100 * np.percentile(m, 2.5), 100 * np.percentile(m, 97.5)

rows = []
for f in sorted(glob.glob(f"{ROOT}/results/raw/errbars_*/metrics.json")):
    r = json.load(open(f)); R = r["runs"]; seeds = [v for k, v in R.items() if k.startswith("cfkv_seed")]
    if len(seeds) < 2:
        continue
    model, j = r["model"], int(r["j"]); name, L = NAMES[model]
    row = {"model": model, "name": name, "j": j, "skip": round(100 * (L - j) / L), "n_seeds": len(seeds), "run": os.path.basename(os.path.dirname(f))}
    for t in ("mmlu", "gsm8k"):
        cf = np.array([s[t] for s in seeds]) * 100
        items = np.mean([np.array(s[f"{t}_items"], dtype=float) for s in seeds], 0)
        pop = np.array(R["pop"][f"{t}_items"], dtype=float)
        d, lo, hi = boot(items - pop)
        row[t] = {"exact": 100 * R["exact"][t], "pop": 100 * R["pop"][t], "cf_mean": cf.mean(), "cf_sd": cf.std(ddof=1), "gain": d, "lo": lo, "hi": hi}
    rows.append(row)
rows.sort(key=lambda r: (ORDER.index(r["model"]), -r["j"]))
L_ = [r"\begin{table*}[t]", r"\centering\small", r"\setlength{\tabcolsep}{4pt}",
      r"\caption{Calibration-sample variability and significance ($w=0$). \ours{} is refitted on five independent calibration samples of the default size (drawn from a pool about 2.5 times larger); mean $\pm$ standard deviation over the refits. Gain over POP: paired bootstrap over items of the refit-averaged per-item correctness (95\% interval, 10{,}000 resamples). MMLU: 1{,}000 questions; GSM8K: 500 problems.}",
      r"\label{tab:errbars}", r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{lc|ccc c|ccc c}", r"\toprule",
      r" & & \multicolumn{4}{c|}{MMLU} & \multicolumn{4}{c}{GSM8K} \\",
      r"Model & Skipped & Full & POP & \ours{} & Gain over POP & Full & POP & \ours{} & Gain over POP \\", r"\midrule"]
for r in rows:
    cells = []
    for t in ("mmlu", "gsm8k"):
        x = r[t]
        cells += [f"{x['exact']:.1f}", f"{x['pop']:.1f}", f"{x['cf_mean']:.1f} $\\pm$ {x['cf_sd']:.1f}", f"$+{x['gain']:.1f}$ [{x['lo']:+.1f}, {x['hi']:+.1f}]" if x['gain'] >= 0 else f"${x['gain']:.1f}$ [{x['lo']:+.1f}, {x['hi']:+.1f}]"]
    L_.append(f"{r['name']} ($j{{=}}{r['j']}$) & {r['skip']}\\% & " + " & ".join(cells) + r" \\")
L_ += [r"\bottomrule", r"\end{tabular}}", r"\end{table*}"]
open(f"{ROOT}/paper/table_errbars.tex", "w").write("% generated by scripts/make_errbars_table.py\n" + "\n".join(L_) + "\n")
for r in rows:
    print(f"{r['name']:13s} j={r['j']:2d} ({r['skip']}%) seeds={r['n_seeds']} | MMLU full {r['mmlu']['exact']:.1f} POP {r['mmlu']['pop']:.1f} CF {r['mmlu']['cf_mean']:.1f}+-{r['mmlu']['cf_sd']:.2f} gain {r['mmlu']['gain']:+.1f} [{r['mmlu']['lo']:+.1f},{r['mmlu']['hi']:+.1f}]"
          f" | GSM8K full {r['gsm8k']['exact']:.1f} POP {r['gsm8k']['pop']:.1f} CF {r['gsm8k']['cf_mean']:.1f}+-{r['gsm8k']['cf_sd']:.2f} gain {r['gsm8k']['gain']:+.1f} [{r['gsm8k']['lo']:+.1f},{r['gsm8k']['hi']:+.1f}]  ({r['run']})")
