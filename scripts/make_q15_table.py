"""Appendix table: Qwen2.5-1.5B at two depths with token-selection baselines at matched compute (results/raw/me_qwen1.5b_*)."""
import json, glob, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = [("GSM8K", "gsm8k"), ("MATH-500", "math500"), ("HumanEval", "humaneval"), ("MBPP", "mbpp"), ("CNN/DM", "cnndm"),
     ("MMLU", "mmlu"), ("ARC-C", "arc"), ("HellaSwag", "hellaswag")]
EX = [69.6, 50.8, 59.8, 48.8, 20.1, 60.8, 76.3, 69.1]
r = {}
for f in sorted(glob.glob(f"{ROOT}/results/raw/me_qwen1.5b_*/metrics.json")):
    for t, d in json.load(open(f))["results"].items():
        for k, v in d.items():
            r.setdefault(t, {})[k] = 100 * v["score"]
M = [("\\ours{}", "cfkv"), ("POP", "pop"), ("FastKV", "fastkv"), ("Selection + \\ours{}", "selcfkv"), ("Drop", "drop")]
L = [r"\begin{table*}[t]", r"\centering\small", r"\setlength{\tabcolsep}{4pt}",
     r"\caption{Qwen2.5-1.5B at two depths, with token-selection baselines at matched prefill compute: selection at layer 7 "
     r"keeps the fraction of context tokens that makes its saving equal to the depth's (fraction 0.57 for one third, 0.33 for "
     r"half), dropping the rest from the upper layers; selection + \ours{} predicts them with a map fitted at layer 7. "
     r"Bold: best method per column and panel.}", r"\label{tab:q15matched}",
     r"\begin{tabular}{l" + "c" * len(T) + r"|c}", r"\toprule", " & " + " & ".join(b for b, _ in T) + r" & Avg \\",
     r"\midrule", "Full model & " + " & ".join(f"{v:.1f}" for v in EX) + f" & {sum(EX)/8:.1f}" + r" \\"]
for j, title in ((19, r"one third skipped ($j{=}19$)"), (14, r"half skipped ($j{=}14$)")):
    L += [r"\midrule", r"\multicolumn{%d}{c}{\textbf{%s}} \\" % (len(T) + 2, title)]
    vals = {m: [r[t][f"{k}_j{j}"] for _, t in T] for m, k in M}
    best = [max(vals[m][c] for m, _ in M) for c in range(len(T))]; bavg = max(sum(v) / 8 for v in vals.values())
    for m, _ in M:
        cells = [(r"\textbf{%.1f}" % v) if v == best[c] else "%.1f" % v for c, v in enumerate(vals[m])]
        a = sum(vals[m]) / 8
        L.append(m + " & " + " & ".join(cells) + " & " + ((r"\textbf{%.1f}" % a) if a == bavg else "%.1f" % a) + r" \\")
L += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
open(f"{ROOT}/paper/table_q15_matched.tex", "w").write("% generated by scripts/make_q15_table.py\n" + "\n".join(L) + "\n")
print("ok")
