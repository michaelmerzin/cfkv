"""Appendix table: MMLU agreement with the full model's answers (w=0 and w=64), from round2 metrics."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNS = [("Qwen2.5-1.5B", "r2_qwen1.5b_mmlu_0926_2250", (19, 14, 10), 28),
        ("Qwen2.5-7B", "r2_qwen7b_mmlu_0926_2250", (19, 14, 10), 28),
        ("Llama-3.1-8B", "r2_llama8b_mmlu_0926_2250", (22, 16, 12), 32),
        ("Mistral-7B", "r2_mistral7b_mmlu_0927_1527", (22, 16, 12), 32)]
lines = [r"\begin{table}[h]\centering\small",
         r"\caption{MMLU agreement with the full model's answers (\%), 1{,}000 questions.}\label{tab:agree}",
         r"\begin{tabular}{llccc@{\hskip 12pt}ccc}\toprule",
         r" & & \multicolumn{3}{c}{$w=0$} & \multicolumn{3}{c}{$w=64$} \\",
         r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
         r"Model & Skip & \ours{} & POP & Drop & \ours{} & POP & Drop \\\midrule"]
for bi, (name, run, js, L) in enumerate(RUNS):
    m = json.load(open(f"{ROOT}/results/raw/{run}/metrics.json"))["mmlu"]
    for k, j in enumerate(js):
        cells = []
        for w in (0, 64):
            vals = [100 * m[f"{mode}_j{j}_w{w}"]["agree_with_exact"] for mode in ("predict", "naive", "drop")]
            best = max(vals)
            cells += [(r"\textbf{%.1f}" % v) if v == best else "%.1f" % v for v in vals]
        skip = {19: "32", 14: "50", 10: "64", 22: "31", 16: "50", 12: "62.5"}[j] + "\\%"
        lines.append((name if k == 0 else "") + f" & {skip} & " + " & ".join(cells) + r" \\")
    if bi < len(RUNS) - 1:
        lines.append(r"\midrule")
lines += [r"\bottomrule\end{tabular}\end{table}"]
open(f"{ROOT}/paper/table_agree.tex", "w").write("% generated by scripts/make_agree_table.py\n" + "\n".join(lines) + "\n")
print("\n".join(lines))
