"""Benchmark quality through the timed compute-saving implementation (src/fastpath_eval.py): accuracy of the timed path and of the
evaluation engine on the same items, agreement, and per-prompt prefill latency. Writes paper/table_fastpath.tex."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
r = json.load(open(f"{ROOT}/results/raw/fpe_qwen7b_j14/metrics.json"))
L = [r"\begin{table}[t]", r"\centering\small", r"\setlength{\tabcolsep}{3pt}",
     r"\caption{Benchmark accuracy through the timed implementation of Table~\ref{tab:ttft} (Qwen2.5-7B, half depth, batch 1) and through the evaluation engine used for all other tables, on the same items. Agreement: identical MMLU answers, or GSM8K final answers. Prefill: median per prompt; the exact model is the standard HF forward. Speedup is small on these short prompts and grows with length (Table~\ref{tab:ttft}).}",
     r"\label{tab:fastpath}", r"\begin{adjustbox}{max width=\columnwidth}\begin{tabular}{llcccc}", r"\toprule",
     r"Task & $w$ & Timed path & Engine & Agreement & Prefill (ms) \\", r"\midrule"]
for t, name, n in (("mmlu", "MMLU", r["mmlu"]["0"]["n"]), ("gsm8k", "GSM8K", r["gsm8k"]["0"]["n"])):
    for w in ("0", "64"):
        x = r[t][w]
        ag = x.get("agreement", x.get("answer_agreement"))
        pre = f"{x['prefill_ms_fast_median']:.1f}" + (f" vs.\\ {x['prefill_ms_exact_median']:.1f}" if "prefill_ms_exact_median" in x else "")
        L.append(f"{name} ({n:,}) & {w} & {100*x['acc_fastpath']:.1f} & {100*x['acc_engine']:.1f} & {100*ag:.1f}\\% & {pre} \\\\".replace(",", "{,}") if False else
                 f"{name} ({n}) & {w} & {100*x['acc_fastpath']:.1f} & {100*x['acc_engine']:.1f} & {100*ag:.1f}\\% & {pre} \\\\")
L += [r"\bottomrule", r"\end{tabular}\end{adjustbox}", r"\end{table}"]
open(f"{ROOT}/paper/table_fastpath.tex", "w").write("% generated by scripts/make_fastpath_table.py\n" + "\n".join(L) + "\n")
print("\n".join(L[-7:-3]))
