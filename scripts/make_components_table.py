"""'From POP to CF-KV' build-up table (half depth): held-out fidelity of the predicted keys/values (R^2, mean over the upper layers,
results/raw/analysis_*) and downstream accuracy (GSM8K, HumanEval, MMLU; w=0) for POP -> single-layer ridge -> three-layer ridge
-> + variance-matched keys (= CF-KV). Downstream cells come from the unified runs (me_*: POP and CF-KV) and the ablation runs
(ab_<model>_single_g0, ab_<model>_multi_g0: main_eval --methods cfkv --gammas 0 with --feat single / both). Missing cells print '--'."""
import glob, json, os, statistics as st
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = [("Llama-3.1-8B", "llama8b", "16", "analysis_llama8b_j16_*"), ("Qwen2.5-7B", "qwen7b", "14", "analysis_qwen7b_j14_*")]
TASKS = ["gsm8k", "humaneval", "mmlu"]

def load(pat):
    out = {}
    for f in sorted(glob.glob(f"{ROOT}/results/raw/{pat}/metrics.json")):
        for t, r in json.load(open(f)).get("results", {}).items():
            for k, v in r.items():
                out.setdefault(t, {})[k] = round(100 * v["score"], 1)
    return out

def r2(pat):
    fs = glob.glob(f"{ROOT}/results/raw/{pat}/metrics.json")
    if not fs:
        return None, None, None, None
    L = json.load(open(fs[0]))["layers"]; ks = sorted(L, key=int)[1:]   # layers above j (layer j is exact by construction)
    m = lambda f: st.mean(L[k][f] for k in ks)
    return m("R2_K_pop"), m("R2_V_pop"), m("R2_K_cf"), m("R2_V_cf")

fmt = lambda v, d=1: "--" if v is None else (f"{v:.{d}f}")
SEL = {"llama8b": "both_g0", "qwen7b": "both_g1"}      # configuration selected on validation (Table 1)
rows = {k: [] for k in ("pop", "single_g0", "both_g0", "both_g1")}
for name, tag, j, ap in MODELS:
    kp, vp, kc, vc = r2(ap)
    runs = []
    for f in sorted(glob.glob(f"{ROOT}/results/raw/me_{tag}_*/metrics.json")):
        res = json.load(open(f)).get("results", {}); runs.append((sum(len(r) for r in res.values()), res))
    me = {t: {k: round(100 * v["score"], 1) for k, v in r.items()} for t, r in max(runs, key=lambda r: r[0])[1].items()} if runs else {}
    cell = lambda src, key: [src.get(t, {}).get(key) for t in TASKS]
    rows["pop"].append([kp, vp] + cell(me, f"pop_j{j}"))
    for c in ("single_g0", "both_g0", "both_g1"):
        src = load(f"abc_{tag}_{c}")
        r2c = [kc, vc] if c == "both_g0" else [None, None]
        rows[c].append(r2c + cell(src, f"cfkv_j{j}"))
labels = {"pop": r"POP (special case: $W$ fixed to the layers' own projections)", "single_g0": r"Ridge, one layer ($h^{(j)}$ only)",
          "both_g0": r"\quad + three-layer features ($j$, $j{-}4$, $j{-}8$)", "both_g1": r"\quad + key rescaling ($\gamma=1$)"}
L = [r"\begin{table*}[t]", r"\centering\small", r"\setlength{\tabcolsep}{4pt}",
     r"\caption{From POP to \ours{} at half depth ($w=0$). POP is the point of the linear function class obtained by fixing $W$ to each layer's own projections (Proposition~\ref{prop:pop}); ridge optimizes $W$ over the same class. $R^2$: variance of the true upper-layer keys / values explained on held-out prompt tokens, mean over the upper layers above $j$ (layer $j$ is exact by construction). Accuracy on GSM8K (500), HumanEval (164) and MMLU (1{,}000). The three ridge rows of each model come from one job with the settings of Table~\ref{tab:main} (same machine, batch sizes and items); $^\star$: the configuration selected on validation, which reproduces Table~\ref{tab:main} exactly.}",
     r"\label{tab:components}", r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{lcc|ccc|cc|ccc}", r"\toprule",
     r" & \multicolumn{5}{c|}{" + MODELS[0][0] + r"} & \multicolumn{5}{c}{" + MODELS[1][0] + r"} \\",
     r"\cmidrule(lr){2-6}\cmidrule(lr){7-11}",
     r" & $R^2_K$ & $R^2_V$ & GSM8K & HumanEval & MMLU & $R^2_K$ & $R^2_V$ & GSM8K & HumanEval & MMLU \\", r"\midrule"]
for k in ("pop", "single_g0", "both_g0", "both_g1"):
    cells = []
    for (name, tag, j, ap), v in zip(MODELS, rows[k]):
        cs = [fmt(x, 2) if i < 2 else fmt(x) for i, x in enumerate(v)]
        if SEL.get(tag) == k:
            cs = cs[:2] + [c + r"$^\star$" if c != "--" else c for c in cs[2:]]
        cells += cs
    L.append(labels[k] + " & " + " & ".join(cells) + r" \\")
L += [r"\bottomrule", r"\end{tabular}}", r"\end{table*}"]
open(f"{ROOT}/paper/table_components.tex", "w").write("% generated by scripts/make_components_table.py\n" + "\n".join(L) + "\n")
print("\n".join(L[-7:-3]))
