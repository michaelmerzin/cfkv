"""Appendix table: the CF-KV configuration selected on held-out text (features, alpha, gamma) for every model and depth of Table 1.
One configuration per model and depth, chosen by the last-token KL to the full model and then fixed for all eight benchmarks."""
import glob, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = [("Qwen2.5-1.5B", "qwen1.5b", 28), ("Qwen2.5-7B", "qwen7b", 28), ("Llama-3.1-8B", "llama8b", 32), ("Mistral-7B", "mistral7b", 32), ("Mistral-Small-24B", "mistral24b", 40)]
RUN_GLOB = {"mistral24b": "m24_*"}   # rented-GPU runs
rows = []
for name, tag, L in MODELS:
    cfg = {}
    for f in sorted(glob.glob(f"{ROOT}/results/raw/{RUN_GLOB.get(tag, f'me_{tag}_*')}/metrics.json")):
        for j, v in (json.load(open(f)).get("cfkv_config") or {}).items():
            cfg.setdefault(int(j), v)
    for j in sorted(cfg, reverse=True):
        v = cfg[j]
        feats = ", ".join(str(x) for x in v["feat"])
        pct = 100 * (L - j) / L; pct_s = f"{pct:.1f}" if abs(2 * pct - round(2 * pct)) < 1e-9 and abs(pct - round(pct)) > 1e-9 else str(round(pct))
        rows.append(f"{name} & {j} ({pct_s}\\%) & {feats} & $10^{{{int(round(__import__('math').log10(v['alpha'])))}}}$ & {int(v['gamma'])} & {v['kl']:.3f} \\\\")
L_ = [r"\begin{table}[t]", r"\centering\small", r"\setlength{\tabcolsep}{3pt}",
      r"\caption{\ours{} configuration selected on held-out text for each model and depth of Table~\ref{tab:main}: input layers of the features, ridge strength $\alpha$, key rescaling $\gamma$ and the validation last-token KL. One configuration per model and depth, fixed for all eight benchmarks.}",
      r"\label{tab:configs}", r"\begin{adjustbox}{max width=\columnwidth}\begin{tabular}{llccc c}", r"\toprule", r"Model & $j$ (skipped) & Feature layers & $\alpha$ & $\gamma$ & val.\ KL \\", r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}\end{adjustbox}", r"\end{table}"]
open(f"{ROOT}/paper/table_configs.tex", "w").write("% generated by scripts/make_config_table.py\n" + "\n".join(L_) + "\n")
print("\n".join(rows))
