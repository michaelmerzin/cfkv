"""Size and cost of the CF-KV predictor W for every (model, depth, feature set) used in the paper.
Rows = input features F = (#layers) d + 1; columns = 2 (L-j) n_kv d_h predicted K/V coordinates.
Overhead = predictor FLOPs per context token / FLOPs of the projections and MLP it replaces (attention excluded)."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# (name, d, L, n_kv, d_h, d_ffn, [(j, n_input_layers, label)])
M = [("Qwen2.5-1.5B", 1536, 28, 2, 128, 8960, [(19, 3), (14, 3)]),
     ("Qwen2.5-7B", 3584, 28, 4, 128, 18944, [(19, 3), (14, 3)]),
     ("Llama-3.1-8B", 4096, 32, 8, 128, 14336, [(22, 3), (16, 3)]),
     ("Mistral-7B", 4096, 32, 8, 128, 14336, [(22, 3), (16, 3)]),
     ("Mistral-Small-24B", 5120, 40, 8, 128, 32768, [(27, 3), (20, 3)])]
rows = []
for name, d, L, kv, dh, ffn, cfgs in M:
    for j, nl in cfgs:
        F = nl * d + 1; out = 2 * (L - j) * kv * dh
        params = F * out
        pred_flops = 2 * F * out                                   # per context token
        layer_flops = 2 * (2 * d * d + 2 * d * kv * dh) + 2 * 3 * d * ffn   # q,o + k,v + gated MLP, per token per layer
        rows.append((name, j, nl, F, out, params / 1e6, params * 2 / 2**20, 100 * pred_flops / ((L - j) * layer_flops)))
for r in rows:
    print(f"{r[0]:14s} j={r[1]:2d} layers={r[2]} F={r[3]:6d} out={r[4]:6d} params={r[5]:8.1f}M bf16={r[6]:8.1f}MiB overhead={r[7]:5.1f}%")
L = [r"\begin{table}[t]", r"\centering\small", r"\setlength{\tabcolsep}{4pt}",
     r"\caption{Size and cost of the closed-form predictor $W$ (one matrix per model and depth). $F$: input features ($=\#\text{layers}\cdot d+1$); "
     r"$2(L{-}j)\,n_{kv}d_h$: predicted key/value coordinates; overhead: predictor FLOPs per context token relative to the "
     r"projection and MLP FLOPs of the skipped layers it replaces (attention excluded). bf16 storage.}",
     r"\label{tab:predsize}", r"\begin{adjustbox}{max width=\columnwidth}\begin{tabular}{lccrrrrr}", r"\toprule",
     r"Model & $j$ & layers & $F$ & outputs & params & bf16 & overhead \\", r"\midrule"]
last = None
for r in rows:
    name = r[0] if r[0] != last else ""; last = r[0]
    th = lambda v: f"{v:,}".replace(",", "{,}")
    gib = f"{r[6]/1024:.2f}".replace("0.0", "0.0")
    L.append(f"{name} & {r[1]} & {r[2]} & {th(r[3])} & {th(r[4])} & {r[5]:.0f}M & {gib}\\,GiB & {r[7]:.1f}\\% \\\\")
L += [r"\bottomrule", r"\end{tabular}\end{adjustbox}", r"\end{table}"]
open(f"{ROOT}/paper/table_predsize.tex", "w").write("% generated by scripts/predictor_size.py\n" + "\n".join(L) + "\n")
